#!/usr/bin/env python3
"""Render Inter into anti-aliased bitmap fonts for XenithOS.

Writes shared/font_data.c and shared/font_data.h. Needs Pillow and the Inter OTF files
(Debian/Kali: apt install python3-pil fonts-inter).

    python3 tools/mkfont.py [path/to/inter/otf/folder]

Two sets: the normal one, and the one Settings > Accessibility > Bigger text switches to
(font_sizes[1]). The big headings are already big, so the large set shares their glyphs.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "shared")

# name, file, pixel size
FONTS = [
    ("SMALL",   "Inter-Medium.otf",   17),
    ("BODY",    "Inter-Regular.otf",  21),
    ("BODY_SB", "Inter-SemiBold.otf", 21),
    ("LABEL",   "Inter-SemiBold.otf", 25),
    ("TITLE",   "Inter-Bold.otf",     32),
    ("HEAD",    "Inter-Bold.otf",     46),
    ("BIG",     "Inter-Bold.otf",     64),
]
# Bigger text: these sizes instead (the rest stay as they are).
LARGE = {"SMALL": 22, "BODY": 25, "BODY_SB": 25, "LABEL": 29, "TITLE": 36}
FIRST, LAST = 32, 126


def render(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    cap_top = font.getbbox("H", anchor="ls")[1]          # negative: above the baseline
    glyphs, alpha = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = font.getlength(ch)
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        off = len(alpha)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            alpha += img.tobytes()
        glyphs.append((l, t, w, h, int(round(adv * 64)), off))
    return {"ascent": ascent, "descent": descent, "cap": -cap_top, "glyphs": glyphs, "alpha": bytes(alpha)}


def write_font(f, name, file, size, d):
    f.write(f"/* {file} {size}px */\n")
    f.write(f"static const uint8_t alpha_{name}[{max(1, len(d['alpha']))}] = {{\n")
    a = d["alpha"] or b"\0"
    for i in range(0, len(a), 32):
        f.write("    " + ",".join(str(x) for x in a[i:i + 32]) + ",\n")
    f.write("};\n")
    f.write(f"static const struct font_glyph glyphs_{name}[{LAST - FIRST + 1}] = {{\n")
    for (l, t, w, h, adv, off) in d["glyphs"]:
        f.write(f"    {{{l},{t},{w},{h},{adv},{off}}},\n")
    f.write("};\n\n")


def entry(name, size, d):
    return f"{{{size}, {d['ascent']}, {d['descent']}, {d['cap']}, glyphs_{name}, alpha_{name}}}"


def main():
    fonts = [(name, file, size, render(os.path.join(FONT_DIR, file), size)) for name, file, size in FONTS]
    large = {name: (file, LARGE[name], render(os.path.join(FONT_DIR, file), LARGE[name]))
             for name, file, _ in FONTS if name in LARGE}

    with open(os.path.join(OUT, "font_data.h"), "w", newline="\n") as f:
        f.write("/* Generated by tools/mkfont.py from Inter (SIL Open Font License 1.1). Do not edit. */\n")
        f.write("#ifndef XENITH_FONT_DATA_H\n#define XENITH_FONT_DATA_H\n\n#include <stdint.h>\n\n")
        f.write("struct font_glyph { int16_t x, y; uint8_t w, h; uint16_t adv64; uint32_t off; };\n")
        f.write("struct font { int size, ascent, descent, cap; const struct font_glyph *glyphs; const uint8_t *alpha; };\n\n")
        f.write("enum {\n")
        for name, _, _, _ in fonts:
            f.write(f"    FONT_{name},\n")
        f.write("    FONT_COUNT\n};\n\n")
        f.write(f"#define FONT_FIRST {FIRST}\n#define FONT_LAST {LAST}\n\n")
        f.write("/* The fonts in use: a copy of font_sizes[0] (normal) or font_sizes[1] (bigger text),\n"
                " * which gfx_text_size() switches between. */\n")
        f.write("extern struct font font_table[FONT_COUNT];\n")
        f.write("extern const struct font font_sizes[2][FONT_COUNT];\n\n#endif\n")

    with open(os.path.join(OUT, "font_data.c"), "w", newline="\n") as f:
        f.write("/* Generated by tools/mkfont.py from Inter (SIL Open Font License 1.1). Do not edit. */\n")
        f.write('#include "font_data.h"\n\n')
        for name, file, size, d in fonts:
            write_font(f, name, file, size, d)
        f.write("/* Bigger text */\n")
        for name, (file, size, d) in large.items():
            write_font(f, name + "_L", file, size, d)
        normal = [entry(name, size, d) for name, _, size, d in fonts]
        big = [entry(name + "_L", large[name][1], large[name][2]) if name in large else entry(name, size, d)
               for name, _, size, d in fonts]
        f.write("const struct font font_sizes[2][FONT_COUNT] = {\n    {\n")
        for e in normal:
            f.write(f"        {e},\n")
        f.write("    },\n    {\n")
        for e in big:
            f.write(f"        {e},\n")
        f.write("    },\n};\n\n")
        f.write("struct font font_table[FONT_COUNT] = {\n")
        for e in normal:
            f.write(f"    {e},\n")
        f.write("};\n")

    total = sum(len(d["alpha"]) for *_, d in fonts) + sum(len(d["alpha"]) for _, _, d in large.values())
    print(f"wrote font_data.c: {len(fonts)} fonts and {len(large)} bigger ones, {total // 1024} KB of glyph data")


if __name__ == "__main__":
    main()
